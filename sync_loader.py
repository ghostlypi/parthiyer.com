"""Inline the shared loader before page content. Run after editing its JS/CSS."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
HEAD_START = '<!-- Critical loader styles (generated by sync_loader.py) -->'
HEAD_END = '<!-- End critical loader styles -->'
BODY_START = '<!-- Early loader (generated by sync_loader.py) -->'
BODY_END = '<!-- End early loader -->'


def sync_pages(root=ROOT):
    css = (root / 'css/loader.css').read_text()
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    css = re.sub(r'\s+', ' ', css).strip()
    js = (root / 'js/loader.js').read_text()
    js = re.sub(r'<!--.*?-->', '', js, flags=re.S)
    js = '\n'.join(line.strip() for line in js.splitlines()
                   if line.strip() and not line.lstrip().startswith('//'))
    body = (BODY_START + '\n<div id="loader-wrapper">'
            '<div class="loader-container"></div></div>\n'
            '<script>' + js + '</script>\n' + BODY_END)
    updated = []
    for page in sorted(root.rglob('*.html')):
        raw = page.read_bytes()
        original = raw.decode()
        if 'id="loader-wrapper"' not in original:
            continue
        newline = '\r\n' if b'\r\n' in raw else '\n'
        html = original.replace('\r\n', '\n')
        html = re.sub(re.escape(HEAD_START) + r'.*?' + re.escape(HEAD_END),
                      '', html, flags=re.S)
        # These sources are now delivered inline, with no extra request.
        html = re.sub(r'\s*<link\b[^>]*href="(?:\.\./)?css/loader\.css"[^>]*>', '', html)
        html = re.sub(r'\s*<script src="(?:\.\./)?js/loader\.js"></script>', '', html)
        fallback = []

        def stylesheet(match):
            tag = match.group()
            if not re.search(r'rel="stylesheet"', tag):
                return tag
            tag = re.sub(r'\s+media="print"', '', tag)
            tag = re.sub(r'\s+onload="this\.media=\x27all\x27"', '', tag)
            if not re.search(r'href="[^"]+"', tag):
                return tag
            tag = re.sub(r'\s*/?>$', '>', tag)
            fallback.append(tag)
            return re.sub(r'\s*/?>$', ' media="print" onload="this.media=\x27all\x27">', tag)

        head, rest = html.split('</head>', 1)
        head = re.sub(r'<link\b[^>]*>', stylesheet, head)
        critical = (HEAD_START + '\n<style>' + css + '</style>\n'
                    '<noscript><style>#loader-wrapper{display:none}</style>'
                    + ''.join(fallback) + '</noscript>\n' + HEAD_END)
        head = head.rstrip() + '\n' + critical + '\n'
        html = head + '</head>' + rest
        if BODY_START in html:
            html = re.sub(re.escape(BODY_START) + r'.*?' + re.escape(BODY_END),
                          lambda _: body, html, flags=re.S)
        else:
            # Existing four nested divs: wrapper, container, liquid, bubbles.
            html, count = re.subn(
                r'<div id="loader-wrapper">.*?</div>\s*</div>\s*</div>\s*</div>',
                lambda _: body, html, count=1, flags=re.S)
            if count != 1:
                raise ValueError(f'Unrecognized loader markup: {page}')
        result = html.replace('\n', newline)
        if result != original:
            page.write_bytes(result.encode())
            updated.append(page.relative_to(root))
    return updated


if __name__ == '__main__':
    for page in sync_pages():
        print(page)
